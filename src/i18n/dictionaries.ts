export const DICTIONARIES: Record<Locale, Dictionary> = { sr, en };

/** "{n} ponuda" → "3 ponude" using CLDR plural rules for the locale. */
export function plural(locale: Locale, n: number, forms: Plural): string {
  const rule = new Intl.PluralRules(locale === "sr" ? "sr-Latn" : "en").select(n);
  const form = rule === "one" ? forms.one : rule === "few" && forms.few ? forms.few : forms.other;
  return form.replace("{n}", n.toLocaleString(locale === "sr" ? "sr-Latn-RS" : "en-GB"));
}

/** Simple "{key}" interpolation. */
export function t(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
